#!/usr/bin/env python3
"""Pin the installed Riot Client so a broken self-update cannot replace a working one.

Riot Client 142 (Electron 43) crashes under Darling on missing frameworks, and the
updater replaces the working bundle on the next launch. This tool reports the installed
release, disables or re-enables self-update, discards a staged update, and keeps a
restorable copy of the bundle it found. It never modifies anything but the
`enable_self_update` line and the staged `.partial-*` directory it is asked to remove.
"""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time

SELF_UPDATE = 'enable_self_update:'
PARTIAL_PREFIX = 'Riot Client.app.partial-'
KNOWN_GOOD_RELEASE = '42E1358C87FB3ABC'   # Riot Client 141.0.7.5129, the last release that runs.


def runtime_prefix(explicit=None):
    """The prefix, from --prefix, then DARLING_PREFIX/DPREFIX, then the configured default."""
    if explicit:
        return Path(explicit).expanduser()
    for name in ('DARLING_PREFIX', 'DPREFIX'):
        if os.environ.get(name):
            return Path(os.environ[name]).expanduser()
    config = Path(__file__).resolve().parent.parent / 'build/config.json'
    try:
        return Path(json.loads(config.read_text())['prefix'])
    except (OSError, ValueError, KeyError):
        return Path.home() / '.darling'


def install_paths(prefix):
    """The installed bundle and the update metadata that names its release."""
    shared = Path(prefix) / 'Users/Shared/Riot Games'
    return shared / 'Riot Client.app', shared / 'Metadata/Riot Client'


def release_id(metadata):
    """The release id from `Riot Client.ok`, which holds the CDN manifest URL."""
    try:
        text = (Path(metadata) / 'Riot Client.ok').read_text()
    except OSError:
        return None
    found = re.search(r'/releases/([0-9A-Fa-f]{16})\.manifest', text)
    return found.group(1).upper() if found else None


def self_update_enabled(app):
    """True/False from system.yaml, or None when the setting is absent or unreadable."""
    try:
        text = (Path(app) / 'Contents/Resources/system.yaml').read_text()
    except OSError:
        return None
    for line in text.splitlines():
        if line.strip().startswith(SELF_UPDATE):
            return line.split(':', 1)[1].strip().lower() in ('true', 'yes', '1')
    return None


def staged_updates(app):
    """Half-written bundles the updater would resume on the next launch."""
    app = Path(app)
    try:
        return sorted(entry for entry in app.parent.iterdir()
                      if entry.name.startswith(PARTIAL_PREFIX))
    except OSError:
        return []


def running(proc_root='/proc'):
    """True when a Riot Client process of any prefix is alive; edits then race the updater.

    Only the executable is inspected. Matching the whole command line also hit any
    shell, editor or `grep` that merely named the bundle path, including the command
    that asked for the pin, so a relative `system.yaml` open would block every write.
    """
    for entry in Path(proc_root).iterdir():
        if not entry.name.isdigit():
            continue
        try:
            fields = (entry / 'cmdline').read_bytes().split(b'\0')
        except OSError:
            continue
        executable = Path(fields[0].decode(errors='replace')).name
        if executable in ('RiotClientServices', 'RiotClientUx') or \
                executable.startswith('Riot Client'):
            return True
    return False


def set_self_update(app, enabled, dry_run=False):
    """Rewrite only the enable_self_update line, atomically; return the new value.

    The file is generated by Riot and carries ~760 lines of unrelated settings, so it is
    edited in place rather than regenerated: one targeted line, everything else verbatim.
    """
    path = Path(app) / 'Contents/Resources/system.yaml'
    text = path.read_text()
    wanted = 'true' if enabled else 'false'
    lines = text.splitlines(keepends=True)
    replaced = 0
    for index, line in enumerate(lines):
        if line.strip().startswith(SELF_UPDATE):
            newline = '\n' if line.endswith('\n') else ''
            lines[index] = f'{SELF_UPDATE} {wanted}{newline}'
            replaced += 1
    if replaced != 1:
        raise SystemExit(f"{path}: expected exactly one '{SELF_UPDATE}' line, found {replaced}")
    if not dry_run:
        staged = path.with_name(path.name + '.new')
        staged.write_text(''.join(lines))
        staged.replace(path)
    return enabled


def copy_tree(source, destination):
    """Copy a bundle, letting the filesystem share blocks when it can (btrfs, xfs, zfs)."""
    subprocess.run(['cp', '-a', '--reflink=auto', str(source), str(destination)], check=True)


def backup(app, metadata, destination, dry_run=False):
    """Keep the installed bundle and its release metadata together, named by release."""
    release = release_id(metadata) or f'unknown-{int(time.time())}'
    target = Path(destination).expanduser() / release
    if target.exists():
        raise SystemExit(f'{target} already exists; remove it or choose another directory')
    if dry_run:
        return target
    target.mkdir(parents=True)
    copy_tree(app, target / Path(app).name)
    if Path(metadata).is_dir():
        copy_tree(metadata, target / 'Metadata')
    (target / 'PIN.txt').write_text(
        f'release {release}\n'
        f"self_update {str(self_update_enabled(target / Path(app).name)).lower()}\n"
        f'backed_up {time.strftime("%Y-%m-%dT%H:%M:%S%z")}\n')
    return target


def restore(app, backup_dir, dry_run=False):
    """Swap a backup in, keeping the replaced bundle next to it instead of deleting it.

    Accepts either the directory `--backup` printed or the directory it was given, so
    `--restore build/riot-client-keep` works whether or not the release level is spelled out.
    """
    root = Path(backup_dir).expanduser()
    source = root / Path(app).name
    if not source.is_dir():
        candidates = sorted(child / Path(app).name for child in root.iterdir()
                            if child.is_dir() and (child / Path(app).name).is_dir()) \
            if root.is_dir() else []
        if len(candidates) != 1:
            raise SystemExit(f'{source} does not exist; pass the directory printed by --backup')
        source = candidates[0]
    app = Path(app)
    replaced = app.with_name(f'{app.name}.replaced-{time.strftime("%Y%m%d-%H%M%S")}')
    if dry_run:
        return replaced
    if app.exists():
        app.rename(replaced)
    copy_tree(source, app)
    return replaced


def describe(prefix):
    app, metadata = install_paths(prefix)
    release = release_id(metadata)
    return {
        'prefix': str(prefix),
        'installed': app.is_dir(),
        'release': release,
        'known_good': release == KNOWN_GOOD_RELEASE,
        'self_update': self_update_enabled(app),
        'staged': [entry.name for entry in staged_updates(app)],
        'client_running': running(),
    }


def report(state):
    if not state['installed']:
        print(f"no Riot Client installed in {state['prefix']}")
        return 1
    print(f"prefix      {state['prefix']}")
    print(f"release     {state['release'] or 'unknown'}"
          f"{' (known good, 141.0.7.5129)' if state['known_good'] else ''}")
    enabled = state['self_update']
    print(f"self-update {'enabled' if enabled else 'disabled' if enabled is False else 'unknown'}")
    print(f"staged      {', '.join(state['staged']) or 'none'}")
    print(f"running     {'yes' if state['client_running'] else 'no'}")
    if enabled and state['staged']:
        print('a staged update will replace this bundle on the next launch; '
              'run --pin --discard-partial to keep it')
    elif enabled:
        print('self-update is on: the next launch may install a release that does not run under Darling')
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(
        description='Inspect and pin the installed Riot Client.',
        epilog='Riot Client 142 crashes under Darling; see docs/TROUBLESHOOTING.md.')
    parser.add_argument('--prefix', help='Darling prefix (default: the configured one)')
    parser.add_argument('--json', action='store_true', help='print the state as JSON')
    parser.add_argument('--dry-run', action='store_true', help='print the plan, change nothing')
    parser.add_argument('--status', action='store_true',
                        help='report the installed release and self-update state (default)')
    update = parser.add_mutually_exclusive_group()
    update.add_argument('--pin', action='store_true', help='disable self-update')
    update.add_argument('--unpin', action='store_true', help='re-enable self-update')
    bundle = parser.add_mutually_exclusive_group()
    bundle.add_argument('--backup', metavar='DIR', help='copy the installed bundle to DIR/<release>')
    bundle.add_argument('--restore', metavar='DIR', help='put a bundle kept by --backup back')
    parser.add_argument('--discard-partial', action='store_true',
                        help='remove staged .partial-* bundles (requires --pin or --unpin)')
    args = parser.parse_args(argv)

    prefix = runtime_prefix(args.prefix)
    app, metadata = install_paths(prefix)
    state = describe(prefix)

    if not state['installed'] and not args.restore:
        print(f"no Riot Client installed in {prefix}; run scripts/installer.sh first",
              file=sys.stderr)
        return 1
    if args.status and any((args.pin, args.unpin, args.backup, args.restore)):
        parser.error('--status only reports; drop the actions or drop --status')
    if args.discard_partial and not (args.pin or args.unpin):
        parser.error('--discard-partial removes files; combine it with --pin or --unpin')

    writing = any((args.pin, args.unpin, args.backup, args.restore, args.discard_partial))
    if writing and state['client_running']:
        print('the Riot Client is running; close it (docs/TROUBLESHOOTING.md) and retry',
              file=sys.stderr)
        return 1

    if args.json:
        print(json.dumps(state, indent=2))
    elif not writing:
        return report(state)

    if args.pin or args.unpin:
        enabled = set_self_update(app, args.unpin, args.dry_run)
        print(f"self-update {'enabled' if enabled else 'disabled'}"
              f"{' (dry run)' if args.dry_run else ''}")
        if args.discard_partial:
            staged = staged_updates(app)
            if not staged:
                print('no staged update to remove')
            for partial in staged:
                print(f"removing {partial}{' (dry run)' if args.dry_run else ''}")
                if not args.dry_run:
                    shutil.rmtree(partial)
    if args.backup:
        target = backup(app, metadata, args.backup, args.dry_run)
        print(f"kept {app} as {target}{' (dry run)' if args.dry_run else ''}")
    if args.restore:
        replaced = restore(app, args.restore, args.dry_run)
        print(f"restored from {args.restore}; previous bundle kept at {replaced}"
              f"{' (dry run)' if args.dry_run else ''}")
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (OSError, subprocess.CalledProcessError) as error:
        raise SystemExit(str(error))
